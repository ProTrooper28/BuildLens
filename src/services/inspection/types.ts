/** One finding: what was checked, what was found, and the evidence behind it. */
export interface InspectionCheck {
  id: string;
  section: InspectionSectionId;
  /** What was checked. */
  title: string;
  /** The short result ("HTTPS enabled", "3 of 6 headers missing"). */
  result: string;
  status: CheckStatus;
  /** One or two sentences a non-technical judge can follow. */
  explanation: string;
  /** Exact file paths, URLs, headers, quotes or page numbers. */
  evidence: string[];
  confidence: "high" | "medium" | "low";
  /** Claim metadata, when the check is a claim. */
  claimKind?: ClaimKind;
  pageRefs?: number[];
}

export interface InspectionSection {
  id: InspectionSectionId;
  letter: string;
  label: string;
  description: string;
  /** One-sentence state of this section. */
  summary: string;
  status: CheckStatus;
  checks: InspectionCheck[];
  /** Explanation shown when the section has no evidence to show. */
  empty: string | null;
}

/* ------------------------------------------------------- claim verification */

/**
 * One row of the CLAIM VERIFICATION table: what the candidate said, where they
 * said it, what each independent source showed, and the verdict.
 */
export interface ClaimVerificationRow {
  id: string;
  claim: string;
  claimType: string;
  /** `PPT — slide 5`, `README`, `Submission form`. */
  source: string;
  pageRefs: number[];
  /** What the repository showed. */
  repository: ClaimSourceFinding;
  /** What the deployed application showed. */
  liveApp: ClaimSourceFinding;
  verdict: ClaimVerdict;
  verdictLabel: string;
  /** Why the verdict was assigned, in plain language. */
  note: string;
  /** File paths / URLs behind the verdict. */
  evidenceRefs: string[];
  /** Verbatim snippets from the readable sources. */
  quotes: string[];
  /** What is missing before the claim could be verified. */
  missingEvidence: string[];
  /** The conflicting evidence, when the verdict is CONTRADICTED. */
  contradiction: string | null;
}

/* ----------------------------------------------------------------- findings */

/**
 * Severity of a finding, in the risk order a judge reads them. Severity — not
 * the order something was discovered — decides what reaches Judge Attention,
 * so a missing README can never outrank a committed secret.
 */
export const FINDING_SEVERITIES = ["critical", "high", "medium", "low", "info"] as const;
export type FindingSeverity = (typeof FINDING_SEVERITIES)[number];

export const FINDING_AREAS = [
  "security",
  "claims",
  "deployment",
  "performance",
  "functionality",
  "documentation",
  "code",
  "evidence",
] as const;
export type FindingArea = (typeof FINDING_AREAS)[number];

export const SEVERITY_LABELS: Record<FindingSeverity, string> = {
  critical: "Critical",
  high: "High",
  medium: "Medium",
  low: "Low",
  info: "Info",
};

export const FINDING_AREA_LABELS: Record<FindingArea, string> = {
  security: "Security",
  claims: "Claim verification",
  deployment: "Deployment",
  performance: "Performance",
  functionality: "Functionality",
  documentation: "Documentation",
  code: "Code quality",
  evidence: "Evidence",
};

/**
 * One grouped, prioritised thing that needs the judge's attention. Findings
 * aggregate related observations (twenty unverified claims become one line with
 * a count and three examples) so the section stays readable.
 */
export interface Finding {
  id: string;
  severity: FindingSeverity;
  area: FindingArea;
  areaLabel: string;
  title: string;
  summary: string;
  items: string[];
  count: number;
  link: { section: InspectionSectionId; label: string };
}

/** A score with the evidence reason behind it, so the judge sees why it moved. */
export interface EvidenceDimension {
  id: string;
  label: string;
  /** null when there was not enough evidence to score the dimension. */
  score: number | null;
  reason: string;
  section: InspectionSectionId;
}

/* --------------------------------------------------------------- deployment */

/**
 * Structured result of the deployed-application inspection (Priority 4 §7).
 *
 * A flat, predictable object instead of unstructured text: one row per thing a
 * judge asks about, each with a status, the observed value and a plain-language
 * detail. `null` rows and `could_not_verify` statuses are honest — they mean the
 * check did not run, never that something failed.
 */
export const DEPLOYMENT_ROW_IDS = [
  "availability",
  "https",
  "response",
  "performance",
  "functionality",
  "security",
  "mobile",
] as const;

export type DeploymentRowId = (typeof DEPLOYMENT_ROW_IDS)[number];

export interface DeploymentRow {
  id: DeploymentRowId;
  label: string;
  status: CheckStatus;
  /** Short observed value: "Online", "Enabled", "200 OK in 420 ms". */
  value: string;
  /** One sentence a non-technical judge can follow. */
  detail: string;
}

export interface DeploymentInspection {
  /** False when this project type does not need a deployed website. */
  applicable: boolean;
  url: string | null;
  /** When the evidence in this object was collected (report build time). */
  checkedAt: string;
  rows: DeploymentRow[];
  /** Raw observation results, kept verbatim. */
  observations: string[];
  /** Exact URLs / status lines behind the rows. */
  evidence: string[];
  /** What was deliberately not tested (never presented as a pass). */
  limitations: string[];
}

/* ----------------------------------------------------------------- verdict */

export type VerdictTone = "strong" | "promising" | "mixed" | "limited" | "unverified";

export const VERDICT_TONE_LABELS: Record<VerdictTone, string> = {
  strong: "Strong",
  promising: "Promising",
  mixed: "Mixed",
  limited: "Limited evidence",
  unverified: "Not verified",
};

export interface ClaimCounts {
  supported: number;
  partially_supported: number;
  not_found: number;
  could_not_verify: number;
}

/** The verdict counts the claim-verification headline reads out. */
export interface VerdictCounts {
  verified: number;
  partially_verified: number;
  unverified: number;
  unsupported: number;
  contradicted: number;
}

export interface JudgeVerdict {
  /** "Strong project, but 2 major claims could not be verified." */
  headline: string;
  tone: VerdictTone;
  toneLabel: string;
  /** Automated score when a model ran; never invented here. */
  score: number | null;
  aiAvailable: boolean;
  counts: ClaimCounts & { total: number };
  /** Verdict numbers shown above the claim table. */
  verdictCounts: VerdictCounts & { total: number };
  claimed: string[];
  verified: string[];
  unverified: string[];
  problems: string[];
  strengths: string[];
  security: string[];
  /** The CLAIM VERIFICATION table, in reading order. */
  claimsTable: ClaimVerificationRow[];
  /** Grouped, severity-ranked findings — the source of Judge Attention. */
  findings: Finding[];
  /** Only critical / high / medium findings: what a judge must look at. */
  attention: Finding[];
  severityCounts: Record<FindingSeverity, number>;
  /** Evidence-based scores with the reason behind each one. */
  dimensions: EvidenceDimension[];
  /** Candidate-provided metadata: reported, never verified. */
  candidateProvided: CandidateFact[];
  aiSummary: string | null;
  /** 3–5 plain-language bullets under "What the judge should know". */
  judgeBullets: string[];
  projectType: ProjectType;
  projectTypeLabel: string;
  strategy: string;
  /** Inputs that were missing for this project type, phrased as gaps. */
  missingInputs: string[];
  /** Structured deployed-application inspection (never unstructured prose). */
  deployment: DeploymentInspection;
}

export interface InspectionAiMeta {
  available: boolean;
  model: string | null;
  /** Why the model produced no summary, when it produced none. */
  unavailableReason: string | null;
}

export interface InspectionReport {
  generatedAt: string;
  projectType: ProjectType;
  projectTypeLabel: string;
  strategy: string;
  verdict: JudgeVerdict;
  sections: InspectionSection[];
  sources: EvidenceSourceReport[];
  counts: ClaimCounts & { total: number };
  ai: InspectionAiMeta;
  disclaimer: string;
}

