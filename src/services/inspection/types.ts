/**
 * Project inspection — the judge-facing model.
 *
 * Two readers are served by one report:
 *
 *   JudgeVerdict  — plain language, at the top of the evaluation page. What the
 *                   team claims, what was verified, what was not, what looks
 *                   good, what looks wrong and what needs attention. No file
 *                   paths, no headers, no scores to interpret.
 *   sections[]    — the technical evidence behind that summary, one section per
 *                   area (claims, deck, repository, deployment, security,
 *                   performance, functionality, AI, rubric, evidence).
 *
 * Every check names what was checked, what was found, the exact evidence and
 * how confident BuildLens is. Nothing here is generated by the model: the
 * report is built from the evidence bundle and the run's structured result.
 */

